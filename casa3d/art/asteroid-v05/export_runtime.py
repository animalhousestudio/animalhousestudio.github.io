"""Bake the approved Blender materials and sample the surface for Casa3D."""
import base64
import hashlib
import json
import math
from pathlib import Path
import struct
import subprocess
import tempfile

import bpy
from mathutils.bvhtree import BVHTree


OUT = Path(__file__).resolve().parent
PROJECT = OUT.parents[1]
scene = bpy.context.scene
top = bpy.data.objects["Asteroid_Surface"]
rock = bpy.data.objects["Asteroid_Rock"]
assert bpy.data.objects["Asteroid_Root"]["version"] == "v05 authoring review"
scene.render.engine = "CYCLES"
scene.cycles.samples = 1

SIDE = 201
MIN = -50
STEP = .5
TERRAIN_UV_SPAN = 104


def sample_relief():
    """Encode centimetre offsets from the established game profile."""
    tree = BVHTree.FromPolygons([tuple(v.co) for v in top.data.vertices],
                              [tuple(p.vertices) for p in top.data.polygons],all_triangles=True)
    points = [(MIN+i*STEP,MIN+j*STEP) for j in range(SIDE) for i in range(SIDE)]
    game = subprocess.run(["node",str(OUT/"sample_game_terrain.mjs")],
                          input=json.dumps(points),capture_output=True,text=True,encoding="utf-8",check=True)
    layout = json.loads(game.stdout)
    heights = layout["heights"]
    temple = layout["temple"]
    booth_x,booth_z = layout["booth"]
    rim = [tuple(v.co) for v in rock.data.vertices[:160]]
    rim_segments = [(x,-y, bx-x,y-by) for (x,y,_),(bx,by,_) in zip(rim,rim[1:]+rim[:1])]
    values = []
    for (x,z),old in zip(points,heights):
        hit,_,_,_ = tree.ray_cast((x,-z,5),(0,0,-1),20)
        # Preserve the established garden plane and construction pads.
        if hit is None or (-14<=x<=21 and -12<=z<=18):
            values.append(0)
            continue
        garden_distance = max(-14-x,x-21,-12-z,z-18)
        temple_distance = ((x-temple["x"])**2+(z-temple["z"])**2)**.5-2.65
        booth_distance = math.hypot(x-booth_x,z-booth_z)-1.4
        edge_distance = math.inf
        if math.hypot(x,z)>36:
            for ax,az,dx,dz in rim_segments:
                along = min(1,max(0,((x-ax)*dx+(z-az)*dz)/(dx*dx+dz*dz)))
                edge_distance = min(edge_distance,math.hypot(x-ax-dx*along,z-az-dz*along))
        blend = min(1,max(0,min(garden_distance,temple_distance,booth_distance,edge_distance-1.05)/3))
        values.append(round((hit.z-old)*100*blend))
    assert max(map(abs,values)) <= 127
    encoded = base64.b64encode(struct.pack(f"{len(values)}b",*values)).decode()
    lines = "\n".join(f"  '{encoded[i:i+120]}'" for i in range(0,len(encoded),120))
    # Adjacent rows of base64 text are joined by the JavaScript loader.
    profile = (
        "// Generated by art/asteroid-v05/export_runtime.py. Heights in centimetres.\n"
        f"export const RELIEF_GRID = {{ side:{SIDE}, min:{MIN}, step:{STEP} }};\n"
        f"export const RELIEF_BASE64 = [\n{lines.replace(chr(10), ','+chr(10))}\n].join('');\n"
    )
    path = PROJECT/"src/rooms/asteroidReliefData.mjs"
    path.write_text(profile,encoding="utf-8")
    return path, max(map(abs,values))


def bake_color(obj, pixels, temp):
    bpy.ops.object.select_all(action="DESELECT")
    obj.hide_set(False)
    obj.select_set(True)
    bpy.context.view_layer.objects.active = obj
    uv = obj.data.uv_layers.new(name="Terrain UV")
    if obj == top:
        for loop, coord in zip(obj.data.loops,uv.data):
            x,y,_ = obj.data.vertices[loop.vertex_index].co
            coord.uv = (x/TERRAIN_UV_SPAN+.5,y/TERRAIN_UV_SPAN+.5)
    else:
        bpy.ops.object.mode_set(mode="EDIT")
        bpy.ops.mesh.select_all(action="SELECT")
        bpy.ops.uv.smart_project(angle_limit=1.15,island_margin=.007)
        bpy.ops.object.mode_set(mode="OBJECT")

    source = obj.data.materials[0]
    nodes,links = source.node_tree.nodes, source.node_tree.links
    image = bpy.data.images.new(f"{obj.name} Color",pixels,pixels,alpha=False)
    target = nodes.new("ShaderNodeTexImage")
    target.image = image
    nodes.active = target
    emission = nodes.new("ShaderNodeEmission")
    links.new(nodes.get("Principled BSDF").inputs["Base Color"].links[0].from_socket,emission.inputs["Color"])
    links.new(emission.outputs[0],nodes.get("Material Output").inputs["Surface"])
    bpy.ops.object.bake(type="EMIT",margin=8)
    image.file_format = "JPEG"
    image.filepath_raw = str(temp/(obj.name+".jpg"))
    image.save()

    baked = bpy.data.materials.new(obj.name+" | Bake v05")
    baked.use_nodes = True
    bsdf = baked.node_tree.nodes.get("Principled BSDF")
    bsdf.inputs["Roughness"].default_value = .86
    texture = baked.node_tree.nodes.new("ShaderNodeTexImage")
    texture.image = bpy.data.images.load(image.filepath_raw,check_existing=False)
    baked.node_tree.links.new(texture.outputs["Color"],bsdf.inputs["Base Color"])
    obj.data.materials.clear()
    obj.data.materials.append(baked)
    for color in list(obj.data.color_attributes):
        obj.data.color_attributes.remove(color)


profile,max_delta = sample_relief()
with tempfile.TemporaryDirectory() as scratch:
    temp = Path(scratch)
    bake_color(top,1536,temp)
    bake_color(rock,1024,temp)
    bpy.ops.object.select_all(action="DESELECT")
    for obj in (top,rock):
        obj.select_set(True)
    glb = PROJECT/"src/assets/models/asteroid-v05.glb"
    bpy.ops.export_scene.gltf(filepath=str(glb),export_format="GLB",use_selection=True,
                             export_animations=False,export_lights=False,export_cameras=False,
                             export_image_format="JPEG",export_jpeg_quality=86)


def describe(path):
    return {"bytes":path.stat().st_size,"sha256":hashlib.sha256(path.read_bytes()).hexdigest()}


manifest = {
    "source": describe(OUT/"Asteroide_v05.blend"),
    "glb": describe(glb),
    "relief_module": describe(profile),
    "baked_base_color_pixels": [1536,1024],
    "triangles": sum(len(obj.data.polygons) for obj in (top,rock)),
    "max_relief_delta_cm": max_delta,
}
(OUT/"runtime-export.json").write_text(json.dumps(manifest,indent=2)+"\n",encoding="utf-8")
